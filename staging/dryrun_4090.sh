#!/usr/bin/env bash
# =============================================================================
# dryrun_4090.sh — Pilot 005 pipeline STAGING dry-run on a disposable 4090 pod.
#
# Position statement: a staging pod is NOT the evidence chain. Every reading
# this script produces is tooling validation (pipeline mechanics only) — no
# verdicts, nothing enters any evidence archive. FP8 kernel behavior on a 4090
# differs from H100 — this dry-run does not validate kernel-level performance,
# only orchestration, serving, and verdict logic. Stage-15 GPU assertions are
# skipped via sandbox hooks (legitimate in this scenario only).
#
# Usage (on the pod, after pasting the rebuild package):
#   cd ~/pipe005 && bash <package>/staging/dryrun_4090.sh
#
# Prerequisites: python3 + pip + one 4090 on the pod; network reaches
#   HuggingFace. No OpenRouter key is used (judges run as mocks, zero API spend).
# =============================================================================
set -euo pipefail

PKG="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="$HOME/pipe005-dryrun"
CELL_ID="cell-staging-0p6b"
CELL_DIR="$WORK/logs/$CELL_ID"
MOCKENV="$WORK/pilot-env"
say() { echo "[dryrun $(date -u +%H:%M:%S)] $*"; }
die() { echo "FATAL: $*" >&2; exit 1; }
mkdir -p "$CELL_DIR" "$MOCKENV"

# ---------- 0. environment (minimal golden-stack set; CPU-runnable profiling path on 4090) ----------
say "0. python deps (instant if torch/transformers already in the image)"
pip install -q torch transformers datasets accelerate 2>/dev/null || true
python3 -c "import torch, transformers; print('torch', torch.__version__, '| cuda:', torch.cuda.is_available())"

# ---------- 1. staging spec (a data file, generated by this script — not part of the evidence chain) ----------
say "1. staging spec (stand-in cell: Qwen3-0.6B, rev pinned live from HF)"
REV=$(python3 - <<'PY'
import json, urllib.request
d = json.load(urllib.request.urlopen("https://huggingface.co/api/models/Qwen/Qwen3-0.6B", timeout=60))
print(d["sha"])
PY
)
[ -n "$REV" ] || die "cannot pin Qwen3-0.6B HEAD sha from HF"
PRIV="$MOCKENV/spec-private-$CELL_ID.json"
echo '{"note":"staging private segment — no production params"}' > "$PRIV"
chmod 600 "$PRIV"
PSHA=$(sha256sum "$PRIV" | cut -d' ' -f1)
cat > "$WORK/spec-staging.json" <<EOF
{
  "schema": "effiq-spec/v1",
  "cell": { "id": "$CELL_ID", "pilot": "005-staging", "role": "shakedown" },
  "model": {
    "repo_id": "Qwen/Qwen3-0.6B",
    "revision": "$REV",
    "family": "qwen3-dense",
    "max_model_len": 4096,
    "serve_extra_flags": "",
    "profile_scope_regex": "^model\\\\.layers\\\\.\\\\d+\\\\.self_attn\\\\.(q_proj|k_proj|v_proj|o_proj)$"
  },
  "hardware": { "gpu": "H100", "count": 1, "memory_gb": 80 },
  "load": { "trace_source": "synthetic", "trace_filter": "staging synthetic", "lang": "en", "synthetic_seed": 20266900 },
  "generation": { "temperature": 0, "natural_stopping": true, "gen_concurrency": 4, "max_tokens_cap": 256 },
  "rubric": { "file": "rubrics/default-en.md", "lang": "en" },
  "anchors": { "n_frozen": 150, "n_screen": 40, "n_calib_texts": 256,
               "derive_seed": 20266901, "run_seed_base": 20266910, "blind_seed": 20266902,
               "reuse": null },
  "private_segment_sha256": "$PSHA"
}
EOF
python3 "$PKG/pipeline/spec_check.py" "$WORK/spec-staging.json" "$PKG" || die "staging spec failed validation"
say "spec validated (rev=${REV:0:12}…)"

# stage-14 resolves the cell spec at $REPO_DIR/specs/<cell-id>.json (Amendment-04
# rubric lookup). Place the staging spec there for the dry-run duration only —
# staging fixture, removed on exit, never committed.
cp "$WORK/spec-staging.json" "$PKG/specs/$CELL_ID.json"
trap 'rm -f "$PKG/specs/$CELL_ID.json"' EXIT

# ---------- 2. shared env ----------
export EFFIQ_HOME="$WORK/effiq" EFFIQ_REPO_ROOT="$PKG" EFFIQ_CELL_DIR="$CELL_DIR"
export EFFIQ_CELL_ID="$CELL_ID" EFFIQ_SPEC_SHA256="$(sha256sum "$WORK/spec-staging.json" | cut -d' ' -f1)"
export EFFIQ_MODEL="Qwen/Qwen3-0.6B" EFFIQ_MODEL_REV="$REV" EFFIQ_MODEL_FAMILY="qwen3-dense"
export EFFIQ_MAX_MODEL_LEN=4096 EFFIQ_SERVE_EXTRA=""
export EFFIQ_PROFILE_SCOPE='^model\.layers\.\d+\.self_attn\.(q_proj|k_proj|v_proj|o_proj)$'
export EFFIQ_TRACE_SOURCE=synthetic EFFIQ_TRACE_FILTER="staging synthetic" EFFIQ_LANG=en EFFIQ_SYNTHETIC_SEED=20266900
export EFFIQ_TEMPERATURE=0 EFFIQ_GEN_CONC=4 EFFIQ_MAX_TOKENS_CAP=256
export EFFIQ_RUBRIC_FILE="rubrics/default-en.md" EFFIQ_RUBRIC_LANG=en
export EFFIQ_N_FROZEN=150 EFFIQ_N_SCREEN=40 EFFIQ_N_CALIB_TEXTS=256
export EFFIQ_DERIVE_SEED=20266901 EFFIQ_RUN_SEED_BASE=20266910 EFFIQ_BLIND_SEED=20266902
export EFFIQ_PRIVSEG_SHA="$PSHA" EFFIQ_GPU_EXPECT="H100"
export CKPT_ROOT="$WORK/ckpt/$CELL_ID"
echo "not-a-real-key" > "$MOCKENV/openrouter-key" && chmod 600 "$MOCKENV/openrouter-key"
export KEY_FILE="$MOCKENV/openrouter-key"

# ---------- 3. stage 14: judge calibration (mock judges) ----------
say "2. stage 14 judge calibration (MOCK judges — zero API spend)"
mkdir -p "$CELL_DIR/calibration"
python3 - <<'PY'
import json, random
rng = random.Random(7)
cats = ["clarity", "correctness", "completeness", "overall"]
import os
with open(os.environ["EFFIQ_CELL_DIR"] + "/calibration/calibration_samples.jsonl", "w") as f:
    for i in range(24):
        f.write(json.dumps({"id": f"c{i}", "prompt": f"p{i}", "response": f"r{i}",
                            "human_score": rng.randint(3, 10), "category": cats[i % 4]}) + "\n")
PY
STAGE14_MOCK_JUDGE=1 bash "$PKG/pipeline/stages/14-judge-calibration.sh"

# ---------- 4. stage 15: cell preflight (GPU assertions skipped — legitimate 4090 staging hooks) ----------
say "3. stage 15 cell preflight (GPU assert skipped — 4090 staging hook)"
STAGE15_SKIP_GPU=1 STAGE15_SKIP_ENV=1 STAGE15_MOCK_CALIB=1 STAGE15_SKIP_SERVER=1 \
VOLUME_DIR="$WORK/volume" mkdir -p "$WORK/volume" || true
mkdir -p "$WORK/volume"
STAGE15_SKIP_GPU=1 STAGE15_SKIP_ENV=1 STAGE15_MOCK_CALIB=1 STAGE15_SKIP_SERVER=1 \
VOLUME_DIR="$WORK/volume" bash "$PKG/pipeline/stages/15-cell-preflight.sh"

# Real pass: reference generation with the real model on real vLLM (bf16 works
# on 4090) — skipped without blocking the dry-run if vLLM is unavailable
if python3 -c "import vllm" 2>/dev/null; then
  say "3b. real reference generation on 0.6B (vLLM bf16, 4090)"
  S15="$(ls -dt "$CELL_DIR/15-cell-preflight"/run_* | head -1)"
  MODEL_DIR="$CKPT_ROOT/$CELL_ID/base" PORT=8123 MAX_MODEL_LEN=4096 GEN_CONC=4 MAX_TOKENS_CAP=256 TEMPERATURE=0 \
  SERVE_EXTRA="" bash "$PKG/pipeline/lib_generate.sh" \
    --set "$S15/frozen_set.jsonl" --out "$S15/gen_A.jsonl" \
    --set "$S15/screening_set.jsonl" --out "$S15/gen_R.jsonl" || say "WARN: real gen failed — leaving stage-15 mock outputs (staging verdict unaffected)"
else
  say "3b. vLLM absent — gen_A/gen_R stay mock (mechanics already proven)"
fi

# if stage 15 lacks gen_A/gen_R because real generation was skipped, backfill mocks (the dry-run validates mechanics only)
S15="$(ls -dt "$CELL_DIR/15-cell-preflight"/run_* | head -1)"
for pair in "gen_A.jsonl:frozen_set.jsonl" "gen_R.jsonl:screening_set.jsonl"; do
  out="${pair%%:*}"; src="${pair##*:}"
  [ -f "$S15/$out" ] || python3 -c "
import json
rows = [json.loads(l) for l in open('$S15/$src')]
open('$S15/$out','w').write(''.join(json.dumps({'id': r['id'], 'prompt': r['text'], 'output': 'REF ' + r['id']}, sort_keys=True) + chr(10) for r in rows))
print('mock $out written')"
done

# ---------- 5. stage 16: arm screening (REAL profiling on 0.6B; mock build/judge) ----------
say "4. stage 16 arm screening (REAL profiling on 0.6B; mock build/judge)"
# NOTE (recipe discipline): the block below is a SYNTHETIC STAGING FIXTURE —
# generic publicly-documented technique names with round-number stand-in
# parameters. Production recipes never enter any repository (they live
# pod-only, per the recipe discipline); this fixture exists so the mock
# build path has a structurally valid input.
cat > "$MOCKENV/arms-recipes.json" <<'EOF'
{
  "profiling": { "top_k": 6, "mse_rel_threshold": 0.05 },
  "smoothing": { "strength": 0.5 },
  "calibration": { "n_samples": 256, "max_seq_len": 1024 },
  "recipes": {
    "b3-a4-kv": { "arm_id": "b3-a4-kv", "builder": "llmcompressor-oneshot",
      "levers": ["sensitive-layer-exemption:attention", "kv-cache-fp8"],
      "quantization": { "targets": "Linear", "scheme": "FP8_DYNAMIC", "ignore": [] },
      "kv_cache_scheme": { "type": "float", "num_bits": 8 },
      "calibration": { "n_samples": 256, "max_seq_len": 1024 }, "uses_base_model": false }
  }
}
EOF
chmod 600 "$MOCKENV/arms-recipes.json"
# reuse the stage-15 0.6B weight download (staging points straight at it)
mkdir -p "$CKPT_ROOT"
# stage-15 downloads to $CKPT_ROOT/$CELL_ID/base (stage-side layout); expose it
# at $CKPT_ROOT/base for the screening stage's reuse path.
[ -d "$CKPT_ROOT/base" ] || ln -s "$CKPT_ROOT/$CELL_ID/base" "$CKPT_ROOT/base" 2>/dev/null || true
STAGE16_MOCK_BUILD=1 STAGE16_MOCK_JUDGE=1 RECIPES_FILE="$MOCKENV/arms-recipes.json" \
  bash "$PKG/pipeline/stages/16-arm-screening.sh" || die "stage 16 failed"

# ---------- 6. stage 18/19 (mock judges + mock measurement) ----------
say "5. stage 18 single-shot confirm (mock)"
STAGE18_MOCK_BUILD=1 STAGE18_MOCK_JUDGE=1 bash "$PKG/pipeline/stages/18-red-dot-confirm.sh" || [ "$?" = "2" ] || die "stage 18 broke"
say "6. stage 19 dual gates (mock measurement, REAL verdict math)"
STAGE19_MOCK_MEASURE=1 bash "$PKG/pipeline/stages/19-dual-gates.sh" || [ "$?" = "2" ] || die "stage 19 broke"

# ---------- 7. stage 17 (mock frontier) ----------
say "7. stage 17 frontier mapping (mock)"
STAGE17_MOCK=1 LOGS_DIR="$WORK/logs" STAGE17_OUT_DIR="$WORK/logs/objective3/17-frontier-mapping/run_1" \
  bash "$PKG/pipeline/stages/17-frontier-mapping.sh"

say "=== DRY-RUN COMPLETE — pipeline mechanics fully traversed (staging readings do not enter the evidence chain) ==="
find "$CELL_DIR" -name "VERDICT.json" -o -name "winner.json" -o -name "panel.json" | sort
